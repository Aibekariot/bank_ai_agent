def _normalize(text: str) -> str:
    text = text.lower().replace("ё", "е")
    text = re.sub(r"[^a-zа-я0-9]+", " ", text)
    return text.strip()


def is_bank_related(text: str) -> bool:
    """
    Быстрый детерминированный фильтр.
    Возвращает True, если в сообщении есть явный банковский термин.
    """
    normalized = _normalize(text)

    if not normalized:
        return False

    words = set(normalized.split())

    return bool(words & BANK_TERMS)


def is_follow_up_bank_question(history: list[dict]) -> bool:
    """
    Разрешает короткие уточняющие сообщения после банковского вопроса.

    Например:
    Пользователь: Какие карты есть?
    Пользователь: А какая лучше для поездок?

    Второе сообщение само по себе может не содержать слова "карта",
    поэтому смотрим предыдущие сообщения.
    """
    if len(history) < 2:
        return False

    # Проверяем предыдущие пользовательские сообщения.
    for message in reversed(history[:-1]):
        if message.get("role") != "user":
            continue

        text = message.get("text", "")

        if is_bank_related(text):
            return True

    return False


def check_bank_scope(history: list[dict]) -> bool:
    """
    Проверяет, относится ли текущий запрос к банковской теме.
    """
    if not history:
        return False

    current_message = history[-1].get("text", "")

    if is_bank_related(current_message):
        return True

    # Короткое продолжение банковского диалога:
    # "А сколько?", "А для пенсионеров?", "А за границей?"
    if is_follow_up_bank_question(history):
        return True

    return False