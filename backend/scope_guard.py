def _normalize(text: str) -> str:
    text = (text or "").lower().replace("ё", "е")
    text = re.sub(r"[^a-zа-яңөү0-9\-]+", " ", text)
    return text.strip()


_SPACED_LETTERS_RE = re.compile(r"(?:(?<!\w)\w(?!\w) ?){4,}")


def _collapse_spaced_letters(raw: str) -> str:
    """"з а б у д ь" -> "забудь": защита от обхода фильтра пробелами."""
    return _SPACED_LETTERS_RE.sub(lambda m: m.group().replace(" ", "") + " ", raw)


def is_injection(text: str) -> bool:
    raw = (text or "").lower().replace("ё", "е")
    variants = (raw, _collapse_spaced_letters(raw))
    return any(p.search(v) for p in _INJECTION_RE for v in variants)


def is_off_topic(text: str) -> bool:
    """Жёсткая посторонняя тема (блокируется всегда)."""
    raw = (text or "").lower().replace("ё", "е")
    return any(p.search(raw) for p in _HARD_OFF_RE)


def is_soft_off_topic(text: str) -> bool:
    """Мягкая посторонняя тема (блокируется, если нет банковских слов)."""
    raw = (text or "").lower().replace("ё", "е")
    return any(p.search(raw) for p in _SOFT_OFF_RE)


def is_meta_question(text: str) -> bool:
    """Вопрос о самом помощнике: "что ты умеешь", "кто ты"."""
    raw = (text or "").lower().replace("ё", "е")
    return any(p.search(raw) for p in _META_RE)


_MULTI_WORD = tuple(p for p in BANK_PREFIXES if " " in p.strip())
_SINGLE_WORD = tuple(p for p in BANK_PREFIXES if " " not in p.strip())
_FUZZY = tuple(w.replace("ё", "е") for w in FUZZY_WORDS)


def _fuzzy_bank_word(word: str) -> bool:
    """Опечатки вроде "долар", "кридит": близко к известному банковскому слову."""
    if len(word) < 5:
        return False
    for known in _FUZZY:
        if abs(len(word) - len(known)) > 2:
            continue
        if difflib.SequenceMatcher(None, word[: len(known) + 1], known).ratio() >= FUZZY_CUTOFF:
            return True
    return False


def is_bank_related(text: str) -> bool:
    """True, если в сообщении есть банковское слово (любая словоформа или опечатка)."""
    normalized = _normalize(text).replace("ё", "е")
    if not normalized:
        return False

    padded = f" {normalized} "
    if any(p.strip() and f" {p.strip()}" in padded for p in _MULTI_WORD):
        return True

    for word in normalized.split():
        word = word.strip("-")
        if word in BANK_EXACT:
            return True
        if any(word.startswith(prefix) for prefix in _SINGLE_WORD):
            return True

    # Составные слова: "пин-код", "пинкод".
    if re.search(r"\bпин[\s\-]?код|\bpin[\s\-]?code", normalized):
        return True

    return any(_fuzzy_bank_word(w.strip("-")) for w in normalized.split())


def is_courtesy(text: str) -> bool:
    """Приветствие, благодарность или короткая реплика вроде "не понял"."""
    words = _normalize(text).split()
    if not words or len(words) > 4:
        return False
    return all(w in COURTESY for w in words)


def _last_user_texts(history: list[dict], skip_last: bool = True) -> list[str]:
    messages = history[:-1] if skip_last else history
    return [m.get("text", "") for m in messages if m.get("role") == "user"]


def is_follow_up_bank_question(history: list[dict]) -> bool:
    """
    Короткое уточнение к банковскому вопросу: "а сколько стоит?", "почему?".

    Смотрим только на ПРЕДЫДУЩИЙ вопрос пользователя (а не на любой из
    прошлых) и на длину текущего сообщения.
    """
    if len(history) < 2:
        return False

    current = history[-1].get("text", "")
    if len(_normalize(current).split()) > FOLLOW_UP_MAX_WORDS:
        return False

    previous = _last_user_texts(history)
    return bool(previous) and is_bank_related(previous[-1])


def check_bank_scope(history: list[dict]) -> bool:
    """True - сообщение можно передавать модели."""
    if not history:
        return False

    current = history[-1].get("text", "")

    if not _normalize(current):
        return False

    if is_injection(current):
        return False

    if is_off_topic(current):
        return False

    if is_bank_related(current):
        return True

    if is_meta_question(current) or is_courtesy(current):
        return True

    if is_soft_off_topic(current):
        return False

    return is_follow_up_bank_question(history)
