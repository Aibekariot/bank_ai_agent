def _tool_result_size(result) -> int:
    """
    Возвращает размер результата инструмента
    в символах после сериализации JSON.
    """

    try:
        return len(
            json.dumps(
                result,
                ensure_ascii=False
            )
        )

    except Exception:
        return len(str(result))


def run_chat(history: list[dict]) -> str:

    total_started = time.perf_counter()

    # ---------------------------------------------------------
    # Scope guard
    # ---------------------------------------------------------

    scope_started = time.perf_counter()

    if not check_bank_scope(history):

        elapsed = time.perf_counter() - scope_started

        print(
            f"[TIMING] scope_guard: {elapsed:.3f}s"
        )

        print("[scope_guard] rejected")

        return REFUSAL_MESSAGE

    scope_elapsed = time.perf_counter() - scope_started

    print(
        f"[TIMING] scope_guard: {scope_elapsed:.3f}s"
    )

    print("[scope_guard] accepted")

    # ---------------------------------------------------------
    # Создаём LLM
    # ---------------------------------------------------------

    provider = create_llm_provider(
        system_prompt=SYSTEM_PROMPT,
        tool_declarations=TOOL_DECLARATIONS,
    )

    # ---------------------------------------------------------
    # Первый запрос
    # ---------------------------------------------------------

    response = provider.start_chat(history)

    # ---------------------------------------------------------
    # Tool calling loop
    # ---------------------------------------------------------

    max_tool_rounds = 3

    for round_number in range(1, max_tool_rounds + 1):

        print(
            f"[AGENT] tool round #{round_number}"
        )

        if not response.tool_calls:
            break

        tool_results = []

        for tool_call in response.tool_calls:

            tool_name = tool_call.name

            print(
                f"[TOOL] {tool_name}"
            )

            tool_started = time.perf_counter()

            if tool_name not in TOOL_FUNCTIONS:

                tool_result = {
                    "error": f"Неизвестная функция {tool_name}"
                }

            else:

                try:

                    tool_result = TOOL_FUNCTIONS[
                        tool_name
                    ](
                        **tool_call.arguments
                    )

                except Exception as exc:

                    print(
                        f"[TOOL] {tool_name} error: {exc}"
                    )

                    tool_result = {
                        "error": str(exc)
                    }

            tool_elapsed = (
                time.perf_counter()
                - tool_started
            )

            result_size = _tool_result_size(
                tool_result
            )

            print(
                f"[TOOL] {tool_name}: "
                f"{tool_elapsed:.3f}s"
            )

            print(
                f"[TOOL RESULT] {tool_name}: "
                f"{result_size} chars"
            )

            tool_results.append(
                {
                    "id": tool_call.id,
                    "tool_call_id": tool_call.id,
                    "name": tool_name,
                    "result": tool_result,
                }
            )

        response = provider.send_tool_results(
            tool_results
        )

    total_elapsed = (
        time.perf_counter()
        - total_started
    )

    print(
        f"[CHAT] total: {total_elapsed:.3f}s"
    )

    if response.text:
        return response.text

    return (
        "Не удалось получить текстовый ответ "
        "от AI-консультанта."
    )